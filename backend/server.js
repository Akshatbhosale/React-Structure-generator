// Enhanced file system generator with detailed logging
function createFileStructure(node, basePath) {
  const nodePath = path.join(basePath, node.name);
  
  console.log(`🔄 Processing: ${node.name} (${node.type}) at path: ${nodePath}`);
  
  try {
    if (node.type === 'folder') {
      if (!fs.existsSync(nodePath)) {
        fs.mkdirSync(nodePath, { recursive: true });
        console.log(`✅ Created folder: ${nodePath}`);
      } else {
        console.log(`📁 Folder already exists: ${nodePath}`);
      }
      
      // Process children recursively
      if (node.children && node.children.length > 0) {
        console.log(`📂 Processing ${node.children.length} children in ${node.name}`);
        node.children.forEach(child => createFileStructure(child, nodePath));
      } else {
        console.log(`📭 No children in folder: ${node.name}`);
      }
    } else {
      // It's a file
      const content = getFileTemplate(node.name);
      fs.writeFileSync(nodePath, content, 'utf8');
      console.log(`✅ Created file: ${nodePath}`);
      console.log(`📝 File content length: ${content.length} characters`);
    }
  } catch (error) {
    console.error(`❌ Error creating ${nodePath}:`, error.message);
    console.error(`🔍 Error details:`, error);
    throw error;
  }
}

